const { contextBridge, ipcRenderer, webUtils } = require('electron')

const subscribe = (channel, cb) => {
  const listener = (_e, ...args) => cb(...args)
  ipcRenderer.on(channel, listener)
  return () => ipcRenderer.removeListener(channel, listener)
}

contextBridge.exposeInMainWorld('api', {
  importMedia: () => ipcRenderer.invoke('media:import'),
  probeFiles: (files) => ipcRenderer.invoke('media:probe', files.map((f) => webUtils.getPathForFile(f))),
  saveProject: (json, filePath) => ipcRenderer.invoke('project:save', { json, filePath }),
  openProject: () => ipcRenderer.invoke('project:open'),
  initialProject: () => ipcRenderer.invoke('project:initial'),
  openProjectPath: (path) => ipcRenderer.invoke('project:openPath', path),
  recentProjects: () => ipcRenderer.invoke('recent:list'),
  removeRecent: (path) => ipcRenderer.invoke('recent:remove', path),
  showInFolder: (path) => ipcRenderer.invoke('shell:show', path),
  openMicSettings: () => ipcRenderer.invoke('shell:micSettings'),
  openVbCable: () => ipcRenderer.invoke('shell:vbcable'),
  platform: process.platform,
  exportVideo: (payload) => ipcRenderer.invoke('export:start', payload),
  cancelExport: (id) => ipcRenderer.invoke('export:cancel', id),
  clearExports: (id) => ipcRenderer.invoke('export:clear', id),
  listExports: () => ipcRenderer.invoke('export:list'),
  onExportJobs: (cb) => subscribe('export:jobs', cb),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  pickFolder: (title, current) => ipcRenderer.invoke('settings:pickFolder', title, current),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  onUpdateStatus: (cb) => subscribe('update:status', cb),
  makeProxy: (path) => ipcRenderer.invoke('media:proxy', path),
  detectKey: (path, inPoint, duration) => ipcRenderer.invoke('audio:key', path, inPoint, duration),
  extractFrame: (path, time) => ipcRenderer.invoke('media:frame', path, time),
  cleanAudio: (path, inPoint, duration, level) => ipcRenderer.invoke('audio:clean', path, inPoint, duration, level),
  vstStatus: () => ipcRenderer.invoke('vst:status'),
  vstInstall: () => ipcRenderer.invoke('vst:install'),
  vstScan: () => ipcRenderer.invoke('vst:scan'),
  vstEditor: (plugin, state) => ipcRenderer.invoke('vst:editor', plugin, state),
  vstApply: (path, inPoint, duration, plugin, state) => ipcRenderer.invoke('vst:apply', path, inPoint, duration, plugin, state),
  onVstProgress: (cb) => subscribe('vst:progress', cb),
  saveRecording: (data) => ipcRenderer.invoke('record:save', data),
  screenSources: () => ipcRenderer.invoke('screen:sources'),
  screenSelect: (sourceId, systemAudio) => ipcRenderer.invoke('screen:select', sourceId, systemAudio),
  screenBegin: (parts) => ipcRenderer.invoke('screen:begin', parts),
  screenChunk: (id, key, data) => ipcRenderer.invoke('screen:chunk', id, key, data),
  screenFinish: (id) => ipcRenderer.invoke('screen:finish', id),
  screenDiscard: (id) => ipcRenderer.invoke('screen:discard', id),
  screenHotkey: (on) => ipcRenderer.invoke('screen:hotkey', on),
  screenMinimize: (on) => ipcRenderer.invoke('screen:minimize', on),
  onScreenStop: (cb) => subscribe('screen:stop', cb),
  bgPrepare: (path, inPoint, duration) => ipcRenderer.invoke('bg:prepare', path, inPoint, duration),
  bgWriteMasks: (id, data) => ipcRenderer.invoke('bg:writeMasks', id, data),
  bgFinish: (id, hasAudio) => ipcRenderer.invoke('bg:finish', id, hasAudio),
  bgCancel: (id) => ipcRenderer.invoke('bg:cancel', id),
  reverseMedia: (path, inPoint, duration, hasAudio) => ipcRenderer.invoke('media:reverse', path, inPoint, duration, hasAudio),
  onProxyProgress: (cb) => subscribe('proxy:progress', cb),
  pickLut: () => ipcRenderer.invoke('lut:pick'),
  readText: (path) => ipcRenderer.invoke('file:readText', path),
  mixdown: (project, sampleRate) => ipcRenderer.invoke('audio:mixdown', project, sampleRate),
  autosave: (json) => ipcRenderer.invoke('autosave:write', json),
  readAutosave: () => ipcRenderer.invoke('autosave:read'),
  ytdlpStatus: () => ipcRenderer.invoke('ytdlp:status'),
  ytdlpInstall: () => ipcRenderer.invoke('ytdlp:install'),
  ytdlpUpdate: () => ipcRenderer.invoke('ytdlp:update'),
  ytdlpInfo: (url) => ipcRenderer.invoke('ytdlp:info', url),
  ytdlpSearch: (query) => ipcRenderer.invoke('ytdlp:search', query),
  ytdlpDownload: (url, preset) => ipcRenderer.invoke('ytdlp:download', url, preset),
  ytdlpCancel: () => ipcRenderer.invoke('ytdlp:cancel'),
  ytdlpPickFolder: () => ipcRenderer.invoke('ytdlp:pickFolder'),
  onYtdlpProgress: (cb) => subscribe('ytdlp:progress', cb),
  librarySearch: (opts) => ipcRenderer.invoke('library:search', opts),
  libraryDownload: (item) => ipcRenderer.invoke('library:download', item),
  libraryCancel: () => ipcRenderer.invoke('library:cancel'),
  onLibraryProgress: (cb) => subscribe('library:progress', cb),
  stemsStatus: () => ipcRenderer.invoke('stems:status'),
  installStems: (variant) => ipcRenderer.invoke('stems:install', variant),
  separateStems: (req) => ipcRenderer.invoke('stems:separate', req),
  cancelStems: () => ipcRenderer.invoke('stems:cancel'),
  onStemsProgress: (cb) => subscribe('stems:progress', cb),
})
